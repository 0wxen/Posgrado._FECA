<!-- ===== PASOS ===== -->
<section class="seccion seccion-gris">
  <div class="inner">
    <div class="seccion-header">
      <span class="kicker">Procedimiento</span>
      <h2>Pasos del Proceso</h2>
      <p>Desde la liberación de tu trabajo terminal por el sínodo hasta la Cédula Profesional.</p>
    </div>

    <div class="tit-pasos">

      <div class="tit-paso">
        <div class="tit-paso-num">1</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Liberación con el Sínodo</h3>
          <p class="tit-paso-desc">
            Tu director de tesis notifica a la Coordinación Académica que tu trabajo está concluido y
            propone al sínodo (3 integrantes para Especialidad, 5 para Maestría). La Coordinación notifica
            oficialmente a cada sinodal, quienes cuentan con ~20 días hábiles para revisar el documento y
            emitir observaciones. Una vez atendidas, el sínodo libera tu trabajo terminal mediante oficio.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">2</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Pago de Cuotas y Formato de Validación</h3>
          <p class="tit-paso-desc">
            Cubres tres conceptos: carta de no adeudo a biblioteca, Ceremonia Protocolaria (estola y pin) y
            derecho a examen. La Coordinación Académica te entrega el Formato de Validación de Trabajo
            Terminal en tres copias, para recabar las firmas autógrafas del sínodo.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">3</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Entrega del Trabajo Terminal</h3>
          <p class="tit-paso-desc">
            Entregas tu trabajo terminal a la Coordinación Académica de Posgrado siguiendo el formato de
            "Portada y Lineamientos de Entrega", junto con el Consentimiento de Publicación firmado.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">4</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Integración de tu Expediente</h3>
          <p class="tit-paso-desc">
            La Coordinación Académica arma el expediente que se remitirá a la Dirección de Servicios
            Escolares de la UJED: oficio de autorización de la Jefatura de la DEP, tu solicitud de
            autorización, y el Formato de Validación con las firmas del sínodo. La Coordinación
            Administrativa revisa que no tengas adeudos de materias en tu Kardex.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">5</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Entrega ante Servicios Escolares UJED</h3>
          <p class="tit-paso-desc">
            Entregas tu expediente completo (con tu Kardex en dos copias) a la Dirección de Servicios
            Escolares de la UJED, quien emite el Oficio de Autorización para presentar tu examen de grado.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">6</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Ceremonia Protocolaria de Examen de Grado</h3>
          <p class="tit-paso-desc">
            La Coordinación Académica programa la fecha y notifica a ti, tu director y el sínodo. La
            Coordinación Administrativa gestiona el espacio, los símbolos protocolarios y las togas del
            sínodo participante.
          </p>
        </div>
      </div>

      <div class="tit-paso">
        <div class="tit-paso-num">7</div>
        <div class="tit-paso-content">
          <h3 class="tit-paso-titulo">Acta de Examen y Cierre</h3>
          <p class="tit-paso-desc">
            Recibes el Acta de Examen de Grado, que usarás para tramitar tu título profesional ante el
            Edificio Central de la UJED y, posteriormente, tu Cédula Profesional ante la Dirección General
            de Profesiones de la SEP.
          </p>
        </div>
      </div>

    </div><!-- /tit-pasos -->
  </div>
</section>

