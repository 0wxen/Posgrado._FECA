<!-- ===== AVISO DE DURACIÓN ===== -->
<section class="seccion seccion-blanca seccion--compacta">
  <div class="inner">
    <div class="tit-aviso">
      <i class="ti ti-clock"></i>
      <div>
        <strong>Duración total del proceso: aproximadamente 2 meses</strong>
        <p>El proceso de titulación por certificación implica una revisión meticulosa y detallada
        del expediente de cada sustentante: verificación de adeudos académicos, adeudos de pago de
        asignaturas y pendientes administrativos. Se trata de documentación de carácter oficial y de
        alto valor legal, por lo que cada expediente es atendido con el rigor y responsabilidad que
        amerita.</p>
      </div>
    </div>
  </div>
</section>

